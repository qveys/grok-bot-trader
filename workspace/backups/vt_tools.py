def cmd_corr(argv):
    p = argparse.ArgumentParser(prog="backtest.sh corr", description="Correlation + fused-regime detection (no LLM).")
    p.add_argument("--pairs", default="BTC-EUR,ETH-EUR,SOL-EUR")
    p.add_argument("--window", type=int, default=30, help="rolling correlation window (bars)")
    p.add_argument("--edge", type=float, default=0.8, help="|corr| that counts as 'moving together'")
    p.add_argument("--enter", type=float, default=0.9, help="density to enter the fused regime")
    p.add_argument("--exit", type=float, default=0.5, help="density to leave it")
    common_period_args(p)
    a = p.parse_args(argv)
    start, end = resolve_period(a)
    pairs = [x.strip() for x in a.pairs.split(",") if x.strip()]
    dm = fetch_closes(pairs, a.tf, start - dt.timedelta(days=int(a.window * TF_HOURS[a.tf] / 24) + 5), end, a.source)
    rets = pd.DataFrame({k: v["close"].astype(float) for k, v in dm.items()}).pct_change().dropna()
    # method copied from Vibe-Trading skill "correlation-regime" (edge density + hysteresis, causal smoothing)
    n = rets.shape[1]
    mask = np.triu(np.ones((n, n), dtype=bool), k=1)
    dens = pd.Series(np.nan, index=rets.index)
    pair_corr = {}
    for i in range(a.window, len(rets) + 1):
        cm = rets.iloc[i - a.window:i].corr().abs().to_numpy()
        dens.iloc[i - 1] = float((cm[mask] >= a.edge).sum()) / mask.sum()
    sm = dens.rolling(5, min_periods=1).mean()
    fused, states = False, []
    for v in sm.to_numpy():
        if v == v:
            if not fused and v >= a.enter:
                fused = True
            elif fused and v <= a.exit:
                fused = False
        states.append(int(fused))
    st = pd.Series(states, index=rets.index)[dens.notna()]
    trans = st.diff().fillna(0)
    roll = rets.rolling(a.window).corr()
    for x, y in itertools.combinations(rets.columns, 2):
        s = roll.xs(x, level=1)[y] if (x in roll.index.get_level_values(1)) else None
        pair_corr[f"{x}/{y}"] = {"full_period": round(float(rets[x].corr(rets[y])), 3),
                                "last_window": round(float(rets[x].iloc[-a.window:].corr(rets[y].iloc[-a.window:])), 3),
                                "rolling_min": None if s is None else round(float(s.min()), 3)}
    out = {"pairs": list(rets.columns), "timeframe": a.tf, "source": a.source,
           "period": [str(st.index[0]), str(st.index[-1])], "window": a.window, "edge": a.edge,
           "correlations": pair_corr, "current_regime": "FUSED (all move together)" if states[-1] else "NORMAL",
           "share_of_time_fused": round(float(st.mean()), 3),
           "regime_changes": [{"date": str(t), "to": "FUSED" if v > 0 else "NORMAL"} for t, v in trans[trans != 0].items()][-10:],
           "note": "Risk context only (skill says: cannot time tops; not a buy/sell signal)."}
    print(json.dumps(out) if a.json else json.dumps(out, indent=1))
    return 0


