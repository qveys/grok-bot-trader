def cmd_risk(argv):
    p = argparse.ArgumentParser(prog="backtest.sh risk", description="Past falls of a pair vs the team's 8% limit.")
    p.add_argument("--pair", default="BTC-EUR")
    p.add_argument("--limit", type=float, default=8.0, help="drawdown limit in %% (team: 8)")
    p.add_argument("--hold-days", type=int, default=2, help="window for 'how often did price fall X%% within N days'")
    common_period_args(p)
    a = p.parse_args(argv)
    start, end = resolve_period(a)
    from src.quantlib.risk import historical_cvar, historical_var
    df = fetch_closes([a.pair], a.tf, start, end, a.source)[a.pair]
    c = df["close"].astype(float)
    r = c.pct_change().dropna()
    dd = c / c.cummax() - 1
    # episodes below -limit
    below = dd <= -a.limit / 100
    episodes = int(((below) & (~below.shift(1, fill_value=False))).sum())
    bars = int(round(a.hold_days * 24 / TF_HOURS[a.tf]))
    fwd_min = (df["low"].astype(float)[::-1].rolling(bars, min_periods=1).min()[::-1].shift(-1) / c - 1)
    warn = []
    if c.index[0] > start + dt.timedelta(days=3):
        warn.append(f"data only starts {c.index[0]} (requested {start.date()})")
    out = {
        "warnings": warn,
        "pair": a.pair, "timeframe": a.tf, "source": a.source, "period": [str(c.index[0]), str(c.index[-1])], "bars": len(c),
        "max_drawdown_pct": round(float(dd.min()) * 100, 2), "max_drawdown_date": str(dd.idxmin()),
        "current_drawdown_pct": round(float(dd.iloc[-1]) * 100, 2),
        "share_of_time_below_limit": round(float(below.mean()), 3), "episodes_crossing_limit": episodes,
        "worst_bar_pct": round(float(r.min()) * 100, 2), "best_bar_pct": round(float(r.max()) * 100, 2),
        "var95_loss_per_bar_pct": round(historical_var(r.to_numpy(), 0.95) * 100, 2),
        "cvar95_loss_per_bar_pct": round(historical_cvar(r.to_numpy(), 0.95) * 100, 2),
        "var99_loss_per_bar_pct": round(historical_var(r.to_numpy(), 0.99) * 100, 2),
        f"prob_low_hits_minus_{a.limit:g}pct_within_{a.hold_days}d": round(float((fwd_min.dropna() <= -a.limit / 100).mean()), 4),
        "limit_pct": a.limit,
        "note": "VaR95 = a bar loses more than this 1 time in 20; CVaR95 = average loss on those bad bars (quantlib).",
    }
    print(json.dumps(out) if a.json else "\n".join(f"  {k}: {v}" for k, v in out.items()))
    return 0


