"""Non-LLM tools around the Vibe-Trading engine (vibe-trading-ai), spot crypto only.

Sub-commands (default = run):
  run        historical backtest of one rule (spot, long only, leverage 1, no funding)
  robust     overfitting / robustness checks on a rule + a parameter grid
             (Monte Carlo permutation, bootstrap Sharpe CI, walk-forward windows,
              purged walk-forward optimisation, combinatorial purged CV, PBO, deflated Sharpe)
  risk       past falls of a pair (max drawdown, how often -8% happened, VaR/CVaR)
  corr       correlation between pairs + "everything moves together" regime detector
  sentiment  crypto Fear & Greed index (alternative.me, public) + optional text scoring
  journal    read-only analysis of the team's paper trade log (copy, never the original)
  report     1-page PDF/HTML of a run folder (chart + trades)

No LLM, no API key, no broker connector, no order is ever placed. Public market data only.
Run `backtest.sh <command> --help` for options.
"""
