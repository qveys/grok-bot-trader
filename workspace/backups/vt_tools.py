# ───────────────────────── strategy code templates ─────────────────────────
# Each body sets `raw` (float 0/1). mode "state": raw = "want to hold" (exit when 0).
# mode "pulse": raw = entry trigger on a CLOSED candle; exits come from stop / take-profit /
# exit hour / max bars. Fills always happen at the NEXT bar open (engine shifts by 1 bar).
HEADER = '''"""Auto-generated by vt_tools.py (backtest.sh): {desc}"""
from typing import Dict

import numpy as np
import pandas as pd


class SignalEngine:
    def generate(self, data_map: Dict[str, pd.DataFrame]) -> Dict[str, pd.Series]:
        out = {{}}
        for code, df in data_map.items():
            close = df["close"].astype(float)
            high = df["high"].astype(float)
            low = df["low"].astype(float)
            open_ = df["open"].astype(float)
'''
BODIES = {
    "sma_cross": ("state", '''            fast = close.rolling({fast}, min_periods={fast}).mean()
            slow = close.rolling({slow}, min_periods={slow}).mean()
            raw = (fast > slow).astype(float)
            raw[slow.isna()] = 0.0
'''),
    "ema_cross": ("state", '''            fast = close.ewm(span={fast}, adjust=False, min_periods={fast}).mean()
            slow = close.ewm(span={slow}, adjust=False, min_periods={slow}).mean()
            raw = (fast > slow).astype(float)
            raw[slow.isna()] = 0.0
'''),
    "rsi_revert": ("state", '''            delta = close.diff()
            gain = delta.clip(lower=0).ewm(alpha=1.0 / {rsi_period}, adjust=False, min_periods={rsi_period}).mean()
            loss = (-delta.clip(upper=0)).ewm(alpha=1.0 / {rsi_period}, adjust=False, min_periods={rsi_period}).mean()
            rsi = 100 - 100 / (1 + gain / loss.replace(0, np.nan))
            raw = pd.Series(np.nan, index=close.index)
            raw[rsi < {rsi_low}] = 1.0
            raw[rsi > {rsi_high}] = 0.0
            raw = raw.ffill().fillna(0.0)
'''),
    "buy_hold": ("state", '''            raw = pd.Series(1.0, index=close.index)
'''),
    # Team setup A: trend + level + confirmation on a closed candle.
    #   setup  = close above its {trend}-bar average (up regime)
    #   level  = highest high of the previous {lookback} bars
    #   confirm= the candle CLOSES above that level
    "team_breakout": ("pulse", '''            trend = close.rolling({trend}, min_periods={trend}).mean()
            level = high.rolling({lookback}, min_periods={lookback}).max().shift(1)
            raw = ((close > level) & (close > trend)).astype(float)
'''),
    # Team setup B (D-007 style "rebound after a drop"):
    #   setup  = price fell at least {drop_pct}% over the previous {drop_bars} bars
    #   confirm= a green candle that CLOSES above the previous candle's high
    "team_rebound": ("pulse", '''            chg = close / close.shift({drop_bars}) - 1.0
            green = close > open_
            raw = ((chg.shift(1) <= -{drop_frac}) & green & (close > high.shift(1))).astype(float)
'''),
}
FOOTER = '''            raw = raw.fillna(0.0).clip(lower=0.0, upper=1.0)
            mode = "{mode}"
            sess_start = {sess_start}
            sess_end = {sess_end}
            weekdays_only = {weekdays}
            exit_hour = {exit_hour}
            max_bars = {max_bars}
            idx = pd.DatetimeIndex(df.index)
            if idx.tz is None:
                idx = idx.tz_localize("UTC")
            fill = (idx + pd.Timedelta(minutes={bar_minutes})).tz_convert("{tz}")
            hours = np.asarray(fill.hour + fill.minute / 60.0, dtype=float)
            wd = np.asarray(fill.weekday)
            days = np.asarray(fill.strftime("%Y-%m-%d"))
            rv = raw.to_numpy()
            held = 0
            n_held = 0
            entry_day = ""
            vals = np.zeros(len(rv))
            for i in range(len(rv)):
                exited = False
                if held:
                    n_held += 1
                    if mode == "state" and rv[i] <= 0:
                        held = 0
                    if exit_hour >= 0 and (days[i] != entry_day or hours[i] >= exit_hour):
                        held = 0
                    if max_bars > 0 and n_held >= max_bars:
                        held = 0
                    exited = held == 0
                if not held and not exited and rv[i] > 0:
                    ok = True
                    if sess_start >= 0 and not (sess_start <= hours[i] < sess_end):
                        ok = False
                    if weekdays_only and wd[i] >= 5:
                        ok = False
                    if ok:
                        held = 1
                        n_held = 0
                        entry_day = days[i]
                vals[i] = held
            out[code] = pd.Series(vals, index=df.index)
        return out
'''
USED_PARAMS = {
    "sma_cross": ("fast", "slow"), "ema_cross": ("fast", "slow"),
    "rsi_revert": ("rsi_period", "rsi_low", "rsi_high"), "buy_hold": (),
    "team_breakout": ("trend", "lookback"), "team_rebound": ("drop_pct", "drop_hours"),
}


